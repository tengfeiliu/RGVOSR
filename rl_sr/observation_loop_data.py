"""Independent continuation splits, verified F0 reuse and validation selection."""
from pathlib import Path
import json
import math
import random

from PIL import Image
from rl_sr.artifact_store import read_jsonl, write_json_atomic
from rl_sr.schema import adapter_content_sha256, build_sample_key, content_sha256, identity_sha256
from rl_sr.self_refine import source_group


def select_sources(rows, baseline_paths, excluded_groups, counts, seed):
    baseline={str(Path(p).resolve()) for p in baseline_paths}
    forbidden={str(Path(p).resolve()) for p in excluded_groups}
    training_groups={source_group(r) for r in rows if str(Path(r['lq_path']).resolve()) in baseline}
    train,held={},{}
    for row in rows:
        group=source_group(row)
        if str(Path(row['lq_path']).resolve()) in baseline:
            train.setdefault(group,row)
        elif group not in training_groups|forbidden:
            held.setdefault(group,row)
    nt,nv,ne=counts
    if len(train)<nt or len(held)<nv+ne:
        raise ValueError(f'Insufficient independent sources: train={len(train)}, heldout={len(held)}, requested={counts}')
    rng=random.Random(seed); a=sorted(train);b=sorted(held);rng.shuffle(a);rng.shuffle(b)
    return dict(train=[dict(train[g]) for g in a[:nt]],validation=[dict(held[g]) for g in b[:nv]],
                test=[dict(held[g]) for g in b[nv:nv+ne]])


def select_checkpoint(base,candidates):
    if not candidates: raise ValueError('No checkpoint candidates')
    keys=('psnr','ssim','lpips','dists')
    if any(r.get('split')!='validation' for r in candidates):
        raise ValueError('Checkpoint selection must use validation only')
    metrics=[base,*candidates,*[r['round4'] for r in candidates if 'round4' in r]]
    if not all(math.isfinite(float(r[k])) for r in metrics for k in keys):
        raise ValueError('Nonfinite checkpoint metric')
    def eligible(r):
        early=(r['psnr']>=base['psnr']+.02 and r['ssim']>=base['ssim']-.002
               and r['lpips']<=base['lpips']+.002 and r['dists']<=base['dists']+.001)
        late=r.get('round4')
        if late is None:return early
        return early and (late['psnr']>=max(base['psnr']+.02,r['psnr']-.02)
            and late['ssim']>=base['ssim']-.002 and late['lpips']<=base['lpips']+.002
            and late['dists']<=base['dists']+.001)
    good=[r for r in candidates if eligible(r)]
    best=max(good or candidates,key=lambda r:(r['psnr']+r.get('round4',r)['psnr'])/2)
    return dict(selected=best['name'],quality_passed=bool(good),selection_split='validation',
                selected_metrics=best,candidates=[{**r,'eligible':eligible(r)} for r in candidates],
                interpretation='Best raw candidate remains reported even when the quality gate fails')


def prepare_run(config,run):
    from models.prompt_builder import build_sr_prompt
    from models.router_condition import extract_router_condition,ROUTER_CONDITION_VERSION
    from rl_sr.stable_reuse import validate_teacher_state
    run=Path(run);run.mkdir(parents=True,exist_ok=True);base=Path(config['baseline_run'])
    if adapter_content_sha256(config['f0_adapter'])!=config['f0_sha256']:
        raise ValueError('Uploaded F0 adapter hash mismatch')
    manifest=json.loads((base/'01_f0_round1_train_state/iterative_manifest.json').read_text())
    if manifest['status']!='completed' or manifest['upscale_policy']['round_1']!=1:
        raise ValueError('F0 producer or first-round geometry incompatible')
    if adapter_content_sha256(manifest['checkpoint_path'])!=config['f0_sha256']:
        raise ValueError('Baseline was generated by a different checkpoint')
    sampling=json.loads((base/'02_f0_bootstrap_trajectory/round_01/inference_manifest.json').read_text())['sampling']
    expected=dict(num_inference_steps=25,schedule='linear',init_mode='pure_noise',sigma_start=1.,
                  seed=manifest['base_seed'],input_upscale=1,uses_refinement_adapter=False)
    if any(sampling.get(k)!=v for k,v in expected.items()): raise ValueError('Baseline F0 sampling mismatch')
    excluded=set();previous=[]
    for directory in config['prior_runs']:
        path=Path(directory)/'split.json'
        if not path.exists():continue
        prior=json.loads(path.read_text())
        for name in ('validation','test'):
            excluded.update(source_group(r) for r in prior.get(name,[]))
        previous.append(dict(path=str(path),sha256=content_sha256(path)))
    source=read_jsonl(config['source_jsonl']);inputs=(base/'00_inputs/train_lq_inputs.txt').read_text().splitlines()
    split=select_sources(source,inputs,excluded,
        tuple(config[k] for k in ('train_sources','validation_sources','test_sources')),config['seed'])
    states=read_jsonl(base/'02_states_for_c.jsonl')
    index={(str(Path(s['runtime']['original_lr']).resolve()),s['round_index']):s for s in states}
    audit=[]
    for name,rows in split.items():
        for row in rows:
            for field in ('lq_path','hq_path'):
                row[field]=str(Path(row[field]).resolve())
                with Image.open(row[field]) as im:
                    if im.size!=(512,512):raise ValueError(f'{field} must be paired 512: {row[field]}')
            sha=content_sha256(row['lq_path'])
            row['_sample_key']=build_sample_key('lsdir_precrop512_v1',f'original_lr/sha256/{sha}',sha)
            profile=(row.get('unipercept_raw') or {}).get('profile') or {}
            row['_prompt']=build_sr_prompt(profile,use_prompt=True,use_suggestions=True,prompt_variant='iqa_suggestion',include_caption=True)
            row['_router_condition']=extract_router_condition(profile,version=ROUTER_CONDITION_VERSION).as_dict()
            row['_split']=name;row['_f0_path']=None
            row['_lr_sha256']=sha;row['_hr_sha256']=content_sha256(row['hq_path'])
            if name=='train':
                row['_teacher_paths']={}
                for k in (2,3,4):
                    state=validate_teacher_state(index[(row['lq_path'],k)],row,config['f0_sha256'])
                    row['_teacher_paths'][str(k)]=state['runtime']['current_sr']
                row['_f0_path']=row['_teacher_paths']['2']
                audit.append(dict(key=row['_sample_key'],path=row['_f0_path'],sha256=content_sha256(row['_f0_path']),producer_seed=manifest['base_seed']))
    core={k:[{a:b for a,b in r.items() if a!='_f0_path'} for r in rows] for k,rows in split.items()}
    core_hash=identity_sha256(core)
    if (run/'split_core.json').exists():
        if identity_sha256(json.loads((run/'split_core.json').read_text()))!=core_hash:
            raise ValueError('Existing immutable split differs')
        split=json.loads((run/'split.json').read_text())
    else:
        write_json_atomic(run/'split_core.json',core);write_json_atomic(run/'split.json',split)
    groups={k:{source_group(r) for r in rows} for k,rows in split.items()}
    if groups['train']&groups['validation'] or groups['train']&groups['test'] or groups['validation']&groups['test']:
        raise ValueError('HR source group leakage')
    provenance=dict(split_core_sha256=core_hash,counts={k:len(v) for k,v in split.items()},
        source_sha256=content_sha256(config['source_jsonl']),f0_sha256=config['f0_sha256'],
        reused_training_f0=len(audit),reused=audit,excluded_previous_groups=len(excluded),prior_splits=previous,
        scope='Independent of continuation training and prior inspected holdout; F0 pretraining overlap not established',
        protocol='RGB full512 [0,1]; PyIQA PSNR/SSIM RGB, LPIPS/DISTS; no border crop')
    write_json_atomic(run/'provenance.json',provenance)
    return provenance
