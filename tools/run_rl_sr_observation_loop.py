"""Train or run the V5 shared observation-constrained SR corrector.

Input is a JSON split with train/validation/test arrays. Each row contains
``lq_path``, ``hq_path`` (train/validation only), and ``_f0_path``. The F0
image must already have been generated by the fixed FLUX.2 Klein checkpoint.
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import json
import random
import sys
from pathlib import Path

import numpy as np
from PIL import Image
import torch
from torch.nn import functional as F

REPO_ROOT = Path(__file__).resolve().parents[1]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from models.sr_observation_loop import ObservationLoop


OPTIONS = dict(lr_mode="spatial", use_round=True, use_state=True)


def image(path: str | Path) -> torch.Tensor:
    with Image.open(path) as im:
        return torch.from_numpy(np.array(im.convert("RGB"), dtype=np.uint8)).permute(2, 0, 1)


def save_image(value: torch.Tensor, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    array = ((value.detach().float().clamp(-1, 1) + 1) * 127.5).round().byte()
    Image.fromarray(array.permute(1, 2, 0).cpu().numpy()).save(path)


def load_split(path: Path, require_hr: bool = True) -> dict:
    split = json.loads(path.read_text())
    if not isinstance(split, dict):
        raise ValueError("Expected a JSON object of train/validation/test arrays")
    seen = {}
    for name, rows in split.items():
        if name not in ("train", "validation", "test") or not isinstance(rows, list):
            raise ValueError("Unexpected split or non-list rows")
        for row in rows:
            fields = ("lq_path", "_f0_path", "hq_path") if require_hr else ("lq_path", "_f0_path")
            for field in fields:
                if field not in row or not Path(row[field]).is_file():
                    raise FileNotFoundError(f"{name}: missing {field}: {row.get(field)}")
            source = row.get("source_hq_path") or row.get("hq_path") or row["lq_path"]
            source = str(Path(source).resolve())
            previous = seen.setdefault(source, name)
            if previous != name:
                raise ValueError(f"Source leakage between {previous} and {name}: {source}")
    return split


def split_digest(split: dict) -> str:
    identity = {name: [{key: row.get(key) for key in ("lq_path", "hq_path", "_f0_path")}
                       for row in rows] for name, rows in split.items()}
    return hashlib.sha256(json.dumps(identity, sort_keys=True).encode()).hexdigest()


def batch(rows: list, indices: list[int], device: str, require_hr: bool = True):
    result = []
    for field in ("_f0_path", "lq_path") + (("hq_path",) if require_hr else ()):
        values = torch.stack([image(rows[i][field]) for i in indices]).to(device, non_blocking=True)
        if values.shape[-2:] != (512, 512):
            raise ValueError("V5 corrector requires paired 512x512 RGB images")
        result.append(values.float() / 127.5 - 1)
    return result


class ImageBank:
    """Cache paired training images as uint8; materialize float only for sampled batches."""

    def __init__(self, rows: list, device: str):
        self.data = {}
        for field in ("_f0_path", "lq_path", "hq_path"):
            values = torch.stack([image(row[field]) for row in rows])
            if values.shape[-2:] != (512, 512):
                raise ValueError("V5 corrector requires paired 512x512 RGB images")
            self.data[field] = values.to(device)

    def take(self, indices: list[int]):
        index = torch.tensor(indices, device=self.data["_f0_path"].device)
        return [self.data[field][index].float() / 127.5 - 1
                for field in ("_f0_path", "lq_path", "hq_path")]


def gradient_loss(pred, target):
    horizontal = (pred[:, :, :, 1:] - pred[:, :, :, :-1]) - (target[:, :, :, 1:] - target[:, :, :, :-1])
    vertical = (pred[:, :, 1:, :] - pred[:, :, :-1, :]) - (target[:, :, 1:, :] - target[:, :, :-1, :])
    return horizontal.abs().mean() + vertical.abs().mean()


def correction_loss(pred, target):
    return (((pred - target).square() + 1e-6).sqrt().mean()
            + .05 * gradient_loss(pred, target)
            + .1 * F.l1_loss(F.avg_pool2d(pred, 4), F.avg_pool2d(target, 4)))


def rollout(model, current, original_lr, rounds=4):
    state = None
    outputs = []
    for round_number in range(2, rounds + 1):
        result = model(current, original_lr, round_number, state=state, **OPTIONS)
        current, state = result["image"].clamp(-1, 1), result["state"]
        outputs.append(current)
    return outputs


def psnr_each(pred, target):
    mse = (pred.float() - target.float()).square().flatten(1).mean(1) / 4
    return (-10 * torch.log10(mse.clamp_min(1e-12))).cpu().tolist()


@torch.no_grad()
def evaluate(model, rows, device, batch_size, output=None, split="validation"):
    model.eval()
    has_hr = all("hq_path" in row and Path(row["hq_path"]).is_file() for row in rows)
    all_scores = {k: [] for k in range(1, 5)}
    table = []
    for start in range(0, len(rows), batch_size):
        indices = list(range(start, min(start + batch_size, len(rows))))
        tensors = batch(rows, indices, device, require_hr=has_hr)
        f0, lr = tensors[:2]
        hr = tensors[2] if has_hr else None
        with torch.autocast("cuda", dtype=torch.bfloat16, enabled=device.startswith("cuda")):
            candidates = [f0] + rollout(model, f0, lr)
        for k, candidate in enumerate(candidates, 1):
            scores = psnr_each(candidate, hr) if has_hr else [None] * len(indices)
            if has_hr:
                all_scores[k].extend(scores)
            for j, score in enumerate(scores):
                row = rows[indices[j]]
                key = row.get("_sample_key") or Path(row["lq_path"]).stem
                table.append(dict(split=split, sample_key=key, round=k, psnr=score))
                if output is not None:
                    save_image(candidate[j], output / split / f"round_{k:02d}" / f"{key}.png")
    summary = {str(k): float(np.mean(values)) for k, values in all_scores.items()} if has_hr else None
    return summary, table


def save_checkpoint(path, model, optimizer, step, identity, settings):
    payload = dict(model={k: v.detach().cpu() for k, v in model.state_dict().items()},
                   optimizer=optimizer.state_dict(), step=step, split_sha256=identity,
                   settings=settings, architecture="V5-C3-recursive")
    temporary = path.with_suffix(".pending.pt")
    torch.save(payload, temporary)
    temporary.replace(path)


def train(args):
    split = load_split(args.split_json)
    if not split.get("train") or not split.get("validation"):
        raise ValueError("Training requires train and validation splits")
    device = args.device
    torch.manual_seed(args.seed)
    random.seed(args.seed)
    identity = split_digest(split)
    out = args.output
    out.mkdir(parents=True, exist_ok=True)
    settings = dict(width=args.width, depth=args.depth, heads=args.heads)
    model = ObservationLoop(**settings).to(device)
    optimizer = torch.optim.AdamW(model.parameters(), lr=args.lr, weight_decay=.01)
    begin = 0
    if args.resume:
        saved = torch.load(args.resume, map_location="cpu", weights_only=True)
        if saved["split_sha256"] != identity or saved["settings"] != settings:
            raise ValueError("Resume data or model architecture differs")
        model.load_state_dict(saved["model"])
        optimizer.load_state_dict(saved["optimizer"])
        begin = saved["step"]
    source = split["train"]
    bank = ImageBank(source, device)
    history = out / "metrics.jsonl"
    for step in range(begin + 1, args.updates + 1):
        model.train()
        rng = random.Random(args.seed + step)
        indices = [rng.randrange(len(source)) for _ in range(args.batch_size)]
        loops = min(3, 1 + (step - 1) // args.curriculum_every)
        optimizer.zero_grad(set_to_none=True)
        total = 0.
        for offset in range(0, len(indices), args.micro_batch):
            current, lr, target = bank.take(indices[offset:offset + args.micro_batch])
            identity_mask = torch.tensor([rng.random() < .1 for _ in range(len(current))], device=device)
            current[identity_mask] = target[identity_mask]
            with torch.autocast("cuda", dtype=torch.bfloat16, enabled=device.startswith("cuda")):
                outputs = rollout(model, current, lr, rounds=loops + 1)
                loss = torch.stack([correction_loss(pred, target) for pred in outputs]).mean()
            weight = len(current) / len(indices)
            (loss * weight).backward()
            total += float(loss.detach()) * weight
        torch.nn.utils.clip_grad_norm_(model.parameters(), 1.)
        optimizer.step()
        if step % args.save_every == 0 or step == args.updates:
            checkpoint = out / f"checkpoint-{step:05d}.pt"
            save_checkpoint(checkpoint, model, optimizer, step, identity, settings)
            scores, _ = evaluate(model, split["validation"], device, args.eval_batch)
            record = dict(step=step, loss=total, validation_psnr=scores, checkpoint=str(checkpoint))
            with history.open("a") as handle:
                handle.write(json.dumps(record) + "\n")
            print(json.dumps(record), flush=True)
        elif step == begin + 1 or step % 20 == 0:
            print(f"step={step}/{args.updates} loops={loops} loss={total:.5f}", flush=True)


def infer(args):
    split = load_split(args.split_json, require_hr=not args.no_hr)
    saved = torch.load(args.checkpoint, map_location="cpu", weights_only=True)
    if saved.get("architecture") == "V5-C3-recursive":
        settings = saved["settings"]
    elif saved.get("arm") == "C3_recursive" and saved.get("options") == OPTIONS:
        state = saved["model"]
        settings = dict(width=state["round_embedding.weight"].shape[1],
                        depth=len({key.split(".")[1] for key in state if key.startswith("blocks.")}),
                        heads=4)
    else:
        raise ValueError("Expected an integrated or original V5 C3 checkpoint")
    if args.strict_split and saved["split_sha256"] != split_digest(split):
        raise ValueError("Inference split differs from training provenance")
    model = ObservationLoop(**settings).to(args.device)
    model.load_state_dict(saved["model"])
    rows = split[args.eval_split][:args.max_samples] if args.max_samples else split[args.eval_split]
    scores, table = evaluate(model, rows, args.device, args.eval_batch, args.output, args.eval_split)
    args.output.mkdir(parents=True, exist_ok=True)
    with (args.output / "per_image_psnr.csv").open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=("split", "sample_key", "round", "psnr"))
        writer.writeheader()
        writer.writerows(table)
    (args.output / "summary.json").write_text(json.dumps(dict(count=len(rows), psnr=scores,
        checkpoint=str(args.checkpoint), protocol="full 512 RGB; raw outputs; F0 fixed"), indent=2))
    print(json.dumps(scores), flush=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    training = sub.add_parser("train")
    training.add_argument("--split-json", type=Path, required=True)
    training.add_argument("--output", type=Path, required=True)
    training.add_argument("--resume", type=Path)
    training.add_argument("--updates", type=int, default=1200)
    training.add_argument("--batch-size", type=int, default=256)
    training.add_argument("--micro-batch", type=int, default=256)
    training.add_argument("--eval-batch", type=int, default=16)
    training.add_argument("--save-every", type=int, default=200)
    training.add_argument("--curriculum-every", type=int, default=400)
    training.add_argument("--lr", type=float, default=2e-4)
    training.add_argument("--width", type=int, default=96)
    training.add_argument("--depth", type=int, default=2)
    training.add_argument("--heads", type=int, default=4)
    training.add_argument("--seed", type=int, default=20261010)
    prediction = sub.add_parser("infer")
    prediction.add_argument("--split-json", type=Path, required=True)
    prediction.add_argument("--checkpoint", type=Path, required=True)
    prediction.add_argument("--eval-split", choices=("train", "validation", "test"), default="test")
    prediction.add_argument("--output", type=Path, required=True)
    prediction.add_argument("--eval-batch", type=int, default=16)
    prediction.add_argument("--max-samples", type=int)
    prediction.add_argument("--strict-split", action="store_true")
    prediction.add_argument("--no-hr", action="store_true", help="Export raw SR rounds without paired metrics")
    args = parser.parse_args()
    args.device = "cuda" if torch.cuda.is_available() else "cpu"
    if args.command == "train":
        if args.batch_size <= 0 or args.micro_batch <= 0 or args.save_every <= 0 or args.curriculum_every <= 0:
            parser.error("Batch sizes and intervals must be positive")
        train(args)
    else:
        infer(args)


if __name__ == "__main__":
    main()
